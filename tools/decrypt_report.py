#!/usr/bin/env python3
"""Decrypt an Interview Arena encrypted report (.enc.json) with the RSA private key.

Usage:
  python tools/decrypt_report.py report.enc.json --private-key ../_keys/interview_report_private.pem
  python tools/decrypt_report.py report.enc.json --private-key key.pem --out report.json
  type report.enc.json | python tools/decrypt_report.py - --private-key key.pem

Package format (produced in the browser):
  {"v":1,"alg":"RSA-OAEP-256+A256GCM+gzip","key":b64,"iv":b64,"data":b64,...}
"""
from __future__ import annotations

import argparse
import base64
import gzip
import json
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding
from cryptography.hazmat.primitives.ciphers.aead import AESGCM


def b64d(s: str) -> bytes:
    s = s.strip().replace("-", "+").replace("_", "/")
    s += "=" * (-len(s) % 4)
    return base64.b64decode(s)


def main() -> int:
    ap = argparse.ArgumentParser(description="Decrypt an Interview Arena report")
    ap.add_argument("package", help="path to .enc.json, or - for stdin")
    ap.add_argument("--private-key", required=True, help="PEM private key generated by tools/gen_keys.py")
    ap.add_argument("--out", help="write decrypted JSON to this path (default: stdout)")
    args = ap.parse_args()

    raw = sys.stdin.read() if args.package == "-" else Path(args.package).read_text(encoding="utf-8")
    pkg = json.loads(raw)

    if pkg.get("alg") != "RSA-OAEP-256+A256GCM+gzip":
        raise SystemExit(f"不支持的算法：{pkg.get('alg')}")

    key = serialization.load_pem_private_key(Path(args.private_key).read_bytes(), password=None)
    aes_key = key.decrypt(
        b64d(pkg["key"]),
        padding.OAEP(mgf=padding.MGF1(algorithm=hashes.SHA256()), algorithm=hashes.SHA256(), label=None),
    )
    payload = AESGCM(aes_key).decrypt(b64d(pkg["iv"]), b64d(pkg["data"]), None)
    plain = gzip.decompress(payload)
    data = json.loads(plain.decode("utf-8"))

    text = json.dumps(data, ensure_ascii=False, indent=2)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"OK -> {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
